"""
High-Frequency PINN-LNN for UKDALE NILM
========================================

Extends test_pinn_lnn_ukdale_specific_splits.py with three HF-specific ideas:

  1. Multi-channel HF input (4 features per 6-second timestep):
       - aggregate power  (W)
       - dP/dt            — finite-difference rate of change; captures
                            the sharp switching transients visible at 6s
       - rolling mean     — 10-step (60 s) local baseline
       - rolling std      — 10-step (60 s) local variability / cycling noise

  2. Dilated CNN pre-encoder:
       Three Conv1d+BN+ReLU+MaxPool layers with growing dilation (1→2→4)
       compress the WIN-length window into WIN//8 steps while widening the
       temporal receptive field, so the LNN sees a compact but multi-scale
       summary of the raw HF signal.

  3. Same PINN loss as the original:
       L_total = L_MSE + lambda * L_phys  [+ weighted BCE after warmup]
       L_phys  = mean(ReLU(sum_i(p_hat_i_raw) - P_agg_raw - epsilon))

Architecture:
    Input  (batch, WIN, 4)
         |
    DilatedCNNEncoder  ->  (batch, WIN//8, hidden)
         |
    AdvancedLiquidTimeLayer  (adaptive tau, input-dependent gate)
         |
    LayerNorm(hidden)
         |
    4 x Linear(hidden, 1)  — one head per appliance
         |
    Output (batch, 4)

Data:
    Training  : dataset/UKDALE_HF_train.csv      (House 1, 2014-11-09)
    Validation: dataset/UKDALE_HF_validation.csv (House 1, 2014-12-07)
    Testing   : dataset/UKDALE_HF_test.csv       (House 5, 2014-08-24)
    Generated by preprocess_hf.py — run that first.
"""

